// The markers that wrap a passage inside a prayer body.
const MARK_OPEN = "[".repeat(2);
const MARK_CLOSE = "]".repeat(2);

/** The prayer shown for a book, with a safe fallback for any book. */
export const getBookPrayer = (book) => {
  const number = Number(book && book.number);
  const found = BOOK_PRAYERS[number];
  if (found) return found;
  const name = book && book.name ? book.name : "this book";
  const reference = `${name} 1:1`;
  return {
    title: `A Prayer for ${name}`,
    body: `Father, as I read ${name}, give me a listening heart and the grace to obey what I read (${MARK_OPEN}${reference}${MARK_CLOSE}).`,
    body_lu: `Musaala, nga nsoma ${name}, nkusaba omuliro okutwala n'obuwali bwange.`
  };
};