/** The key passages of a book, with a safe fallback for any book. */
export const getKeyPassages = (book) => {
  const number = Number(book && book.number);
  const found = KEY_PASSAGES[number];
  if (found && found.length) return found;
  const name = book && book.name ? book.name : "Genesis";
  return [`${name} 1:1`];
};